const CORPUS = { numRuns: 400 };

describe(
  "edit corpus: oracles 1-5 over " +
    "<=6-op sequences",
  () => {
    const sweep = (
      arb: typeof arbEditLipu
    ): void => {
      resetCorpusStats();
      fc.assert(
        fc.property(arb, arbOps, (lipu, ops) => {
          let cur = lipu;
          for (const op of ops) {
            const { lipu: next, applied } =
              applyOp(cur, op);
            const errs = checkOracles(
              cur,
              next,
              applied
            );
            if (errs.length > 0) {
              throw new Error(
                errs.join("; ") +
                  " on op " +
                  JSON.stringify(op)
              );
            }
            cur = next;
          }
          return true;
        }),
        CORPUS
      );
    };

    it("holds over the shaped corpus", () => {
      sweep(arbEditLipu);
      // The OP side of anti-vacuity. A generator
      // that mints every shape is still vacuous if the
      // alphabet never reaches the paths those shapes
      // live on, so the sweep's own reach is asserted
      // here rather than assumed.
      for (const kind of [
        "insert",
        "delete",
        "replace",
        "enter",
        "split",
        "join",
        "paste",
        "paste-multi",
        "delete-across",
      ]) {
        expect(
          corpusStats.ops[kind] ?? 0
        ).toBeGreaterThan(10);
      }
      expect(
        corpusStats.sideOps.sp ?? 0
      ).toBeGreaterThan(50);
      expect(
        corpusStats.sideOps.latin ?? 0
      ).toBeGreaterThan(50);
      expect(
        corpusStats.structuralOps
      ).toBeGreaterThan(50);
      // ...and the ORACLES' gates: an oracle whose
      // precondition never holds is a comment, not a
      // net.
      //
      // MEASURED FLOOR, not a self-exempting one.
      // Oracle 3's gate is keyed to the system under
      // test — it is the edited side's parse
      // fixpoint — so it can close itself as the
      // merge changes, and `open > closed` has
      // enormous slack at the ~80% this actually
      // runs at. The floor is set just under the
      // measurement so that a change which quietly
      // narrows the gate TRIPS instead of
      // coasting.
      expect(
        corpusStats.oracle3Open /
          (corpusStats.oracle3Open +
            corpusStats.oracle3Closed)
      ).toBeGreaterThan(0.76);
      expect(
        corpusStats.oracle4a + corpusStats.oracle4aPrime
      ).toBeGreaterThan(100);
      expect(
        corpusStats.oracle7Compared
      ).toBeGreaterThan(100);
      // The stranding document-level fallback is
      // rare enough that this sweep may not reach
      // it, so its coverage is a TARGETED test
      // ("the stranding fallback branch is
      // reached") rather than a size-dependent
      // assertion that would make this law flap
      // with numRuns.
      // Oracle 4b's conservation clause ADJUDICATES
      // the large majority of the losses it sees, rather
      // than standing down on all of them.
      expect(
        corpusStats.oracle4bAdjudicated
      ).toBeGreaterThan(
        corpusStats.oracle4bExcused
      );
    });

    it(
      "FAMILY 2 (gap-resident latin disabled) — " +
        "oracles 3 and 4a at full strength",
      () => {
        sweep(arbEditLipuPlain);
        // The gap-resident latin shapes are what make a
        // block latin-parse unstable, and family 1
        // measured a large fraction of oracle-3 and
        // oracle-4 checks landing in the weakened
        // domain because of them. With those two shapes
        // off — and everything else identical — the
        // gates stand open almost everywhere, which is
        // the point of running a second family at
        // all.
        //
        // FLOOR RATIONALE. parseFixpoint (this file,
        // below) is `stable(sideNoOp(b)) ===
        // stable(b)`: is a no-op merge on the edited
        // side an identity? Oracle 3's gate is
        // exactly this predicate, so ANY block still
        // holding an interior-punct multi-anchor run
        // that has not yet transitioned to the bound
        // shape is, BY CONSTRUCTION, not a fixpoint
        // — a Latin no-op legitimately changes it
        // (the same one-time transition priced in
        // properties.test.ts's bind-transition split
        // and the doc-merge.test.ts no-op laws).
        // That is not a narrowing defect; it is the
        // gate correctly reporting that a large
        // fraction of the generated corpus is
        // mid-transition (measured: ~40% of
        // generated documents contain a bound-shaped
        // run before any op runs). The floor sits a
        // few points under the measured open ratio
        // at the committed seed, so a change that
        // quietly narrows the gate trips.
        //
        // (A historical note: at 200 runs this
        // sweep measured 91.2% open; the corpus now
        // runs 400, where the generator-artifact
        // failure that once lurked past run 280 is
        // fixed by the classify wrap in
        // test/edit-corpus.ts.)
        expect(
          corpusStats.oracle3Open /
            (corpusStats.oracle3Open +
              corpusStats.oracle3Closed)
        ).toBeGreaterThan(0.88);
        expect(
          corpusStats.oracle4a +
            corpusStats.oracle4aPrime
        ).toBeGreaterThan(corpusStats.oracle4b);
      }
    );

    it(
      "anti-vacuity: the corpus really reaches " +
        "the minted shapes",
      () => {
        let offsets = 0;
        let emptyName = 0;
        let joiners = 0;
        let letterish = 0;
        let interiorRun = 0;
        let crossPair = 0;
        fc.assert(
          fc.property(arbEditLipu, (lipu) => {
            const docSp = lipu.blocks
              .map((b) =>
                b.gaps.map((g) => g.sp).join("")
              )
              .join("\u0000");
            // a STRAY start in one block and a STRAY
            // end in a LATER one: the pair can never
            // promote, because promotion never
            // crosses a Block boundary
            const cs = docSp.indexOf(CARTOUCHE_START);
            const ce = docSp.lastIndexOf(CARTOUCHE_END);
            if (
              cs >= 0 &&
              ce > cs &&
              docSp
                .slice(cs, ce)
                .includes("\u0000")
            ) {
              crossPair += 1;
            }
            for (const b of lipu.blocks) {
              if (
                b.spans.some(
                  (s) =>
                    (s.kind === "long" ||
                      s.kind === "cartouche") &&
                    s.to > s.from &&
                    b.gaps
                      .slice(s.from + 1, s.to + 1)
                      .some((g) =>
                        g.sp.includes("\n\n")
                      )
                )
              ) {
                interiorRun += 1;
              }
              if (
                b.spans.some(
                  (s) =>
                    s.startOffset !== undefined ||
                    s.endOffset !== undefined
                )
              ) {
                offsets += 1;
              }
              if (
                b.spans.some(
                  (s) =>
                    s.kind === "cartouche" &&
                    b.anchors
                      .slice(s.from, s.to + 1)
                      .every(
                        (a) => a.kind !== "word"
                      )
                )
              ) {
                emptyName += 1;
              }
              if (
                b.gaps.some((g) =>
                  [...g.sp].some((ch) =>
                    JOINER_CHARS.has(ch)
                  )
                )
              ) {
                joiners += 1;
              }
              if (
                b.gaps.some((g) =>
                  /\p{L}|\p{M}/u.test(g.latin)
                )
              ) {
                letterish += 1;
              }
            }
            return true;
          }),
          { numRuns: 300 }
        );
        expect(offsets).toBeGreaterThan(10);
        expect(emptyName).toBeGreaterThan(10);
        expect(joiners).toBeGreaterThan(10);
        expect(letterish).toBeGreaterThan(10);
        expect(interiorRun).toBeGreaterThan(10);
        expect(crossPair).toBeGreaterThan(10);
      }
    );

    it(
      "canonicalSegments is pinned: text splits " +
        "at \\n, empties drop, adjacents merge, " +
        "atoms pass through",
      () => {
        expect(
          canonicalSegments([
            { type: "text", text: "a\n\nb" },
            { type: "text", text: "c" },
          ])
        ).toEqual([
          { kind: "text", text: "a" },
          { kind: "break" },
          { kind: "break" },
          { kind: "text", text: "bc" },
        ]);
      }
    );
  }
);

describe(
  "the equal-count reshape's relocation, pinned",
  () => {
    it(
      "positional pairing loses prev-side content " +
        "on re-created anchors and can strand an " +
        "interior \\n\\n gap.latin — EXACT pin",
      () => {
        const W = (w: string) => ({
          kind: "word" as const,
          word: w,
        });
        const prev: Block[] = [
          {
            anchors: [W("toki")],
            gaps: [
              { sp: "", latin: "" },
              { sp: "", latin: "\n\n" },
            ],
            spans: [],
          },
          {
            anchors: [W("pona")],
            gaps: [
              { sp: "", latin: ". " },
              { sp: "", latin: "" },
            ],
            spans: [],
          },
        ];
        // reshape: same count, different boundary —
        // paragraph 0 now holds both words, 1 empty
        const sides: ParsedSide[] = [
          {
            anchors: [W("toki"), W("pona")],
            gaps: ["", " ", ""],
          },
          { anchors: [], gaps: [""] },
        ];
        const out = mergeStructural(
          prev,
          sides,
          "sp"
        );
        // FROZEN (run-derived). Losses this value
        // exhibits, all from POSITIONAL pairing:
        //  1. STRANDED "\n\n": it was paragraph 0's
        //     TRAILING gap.latin — the Latin text of
        //     the paragraph BOUNDARY — and positional
        //     pairing leaves it on toki's owned gap,
        //     so it is now an INTERIOR "\n\n" between
        //     toki and pona inside one paragraph.
        //  2. LOST ". ": prev paragraph 1's leading
        //     gap.latin stays with the now-EMPTY
        //     paragraph 1 instead of following "pona"
        //     into paragraph 0.
        //  3. The "pona" anchor in paragraph 0 is
        //     RE-CREATED (prev paragraph 0 never had
        //     it), so it takes the creation default
        //     rather than carrying prev "pona"'s
        //     gap.latin.
        // The registry accepts exactly this class
        // (the edge-split relocation). The pin
        // exists so any change to it is loud.
        expect(out).toEqual([
          {
            anchors: [W("toki"), W("pona")],
            gaps: [
              { sp: "", latin: "" },
              { sp: " ", latin: "\n\n" },
              { sp: "", latin: "" },
            ],
            spans: [],
          },
          {
            anchors: [],
            gaps: [{ sp: "", latin: ". " }],
            spans: [],
          },
        ]);
      }
    );
  }
);

