// REGISTERED: the WHITESPACE-VERBATIM SPLIT-HALF
// MISALIGNMENT. A verbatim anchor whose text
// contains a space is re-tokenized by the Latin parse
// into two anchors; the rendered-text LCS then matches a
// NEIGHBOURING anchor against one of the halves, and the
// gap.sp bytes next to the seam die. A bare Latin no-op
// is enough. Duplication is irrelevant to the loss — it
// only decides whether oracle 3 notices — which is why
// the reproducer below has three DISTINCT texts.
//
// Registered as an accepted carve-out, so this pin
// asserts the exact CURRENT loss: any change in its
// shape must come past this test (verified
// pre-existing before the alignment-key fix).
describe(
  "accepted: a whitespace verbatim's split halves " +
    "mis-align and eat the neighbouring gap.sp",
  () => {
    it(
      "a bare Latin no-op turns 3 anchors into 4 and " +
        "DESTROYS the cartouche-end byte in gaps[1].sp",
      () => {
        const b: Block = {
          anchors: [
            {
              kind: "verbatim",
              text: "hi there",
              marked: true,
            },
            {
              kind: "verbatim",
              text: "hi",
              marked: true,
            },
            {
              kind: "verbatim",
              text: "yo dude",
              marked: true,
            },
          ],
          gaps: [
            { sp: " ", latin: "" },
            { sp: CARTOUCHE_END, latin: ", " },
            { sp: "\u3000", latin: ", " },
            { sp: "\u3000", latin: "" },
          ],
          spans: [],
        };
        expect(checkBlock(b)).toEqual([]);
        expect(renderLatin(b).text).toBe(
          "hi there, hi, yo dude"
        );
        const out = latinNoOp(b);
        // "hi there" re-tokenizes into "hi" + "there"
        expect(out.anchors).toEqual([
          { kind: "verbatim", text: "hi", marked: true },
          {
            kind: "verbatim",
            text: "there",
            marked: true,
          },
          { kind: "verbatim", text: "hi", marked: true },
          {
            kind: "verbatim",
            text: "yo dude",
            marked: true,
          },
        ]);
        // the exact loss: the CARTOUCHE_END byte is
        // gone, and an IDEO_SPACE has slid one gap left
        expect(
          out.gaps.map((g) => g.sp)
        ).toEqual([" ", "\u3000", " ", " ", "\u3000"]);
        expect(renderSp(b).text).toContain(
          CARTOUCHE_END
        );
        expect(renderSp(out).text).not.toContain(
          CARTOUCHE_END
        );
        // and it is a fixed point: the loss happens
        // once, on the first no-op
        expect(latinNoOp(out)).toEqual(out);
      }
    );
  }
);

// FIXED, by the LCS OCCURRENCE-AWARE SECONDARY
// KEYING in merge.ts. Found by the strengthened
// oracle 4a', which asserts identity for blocks the
// raw parse only appears to destabilize. The defect
// was NOT re-absorption: the rendered-text LCS
// (mergeBlockDetailed's alignKey) paired prev's
// FIRST "-" with next's only "-" and stranded the
// other in a region whose next side held no "-" at
// all, so absorbInto searched an empty haystack and
// the anchor died with its SP bytes. With the
// secondary keying, a key prev holds MORE OFTEN than
// next is disambiguated by FLANKING GAP CONTENT, so
// each occurrence pairs with the right one or with
// none — and this block is a full-identity NO-OP.
// The pin is a regression lock.
describe(
  "duplicate punctuation-only anchor texts " +
    "survive a Latin no-op (secondary keying)",
  () => {
    it(
      "a per-block Latin NO-OP is IDENTITY: every " +
        "anchor and every SP byte survives",
      () => {
        // Two marked verbatim "-" anchors, one of them
        // inside a cartouche that ATOMIZES (its
        // projected name is non-empty, so the
        // covered "-" is hidden behind the atom),
        // plus
        // a "314". The raw Latin parse returns every
        // punctuation-only anchor to gap.latin, so the
        // next side renders "-" ONCE where prev
        // holds it twice — the exact count asymmetry
        // the secondary key disambiguates.
        //
        // Fixture note: a version with EMPTY
        // gap.latin everywhere (zero flanking latin
        // — maximal reparse collapse) stopped
        // working when interior-punctuation runs
        // started binding whole: with no whitespace
        // at all the ENTIRE line — both "-"s, the
        // digit run, and the second "toki" — welds
        // into ONE bound token, losing the tail
        // "toki" as an independent word anchor. A
        // single real space at each seam (a shape
        // any real author actually types) provides
        // the hard boundaries, and "314" (not
        // "3.14") keeps the middle punct-only span
        // dissolving to gap.latin instead of MINTING
        // its own bound anchor (a digit run with an
        // interior dot binds on its own; a pure
        // digit run does not). The reparse-collapse
        // shape — and the secondary-key
        // disambiguation of the two surviving "-"
        // occurrences from flanking gap content — is
        // intact.
        const b: Block = {
          anchors: [
            { kind: "word", word: "ni" },
            { kind: "word", word: "toki" },
            {
              kind: "verbatim",
              text: "axxq",
              marked: true,
            },
            {
              kind: "verbatim",
              text: "-",
              marked: true,
            },
            {
              kind: "verbatim",
              text: "314",
              marked: true,
            },
            {
              kind: "verbatim",
              text: "-",
              marked: true,
            },
            { kind: "word", word: "toki" },
          ],
          gaps: [
            { sp: "", latin: "" },
            { sp: "", latin: " " },
            { sp: STACK, latin: " " },
            { sp: "　", latin: " " },
            { sp: "", latin: " " },
            { sp: "　", latin: " " },
            { sp: "", latin: " " },
            { sp: "", latin: "" },
          ],
          spans: [
            cart(1, 1),
            cart(3, 3),
            cart(5, 6),
          ],
        };
        // a well-formed block: this is not a shape the
        // model rejects, which is the point
        expect(checkBlock(b)).toEqual([]);
        const out = latinNoOp(b);
        // PRE-FIX: two anchors gone — "314" and one
        // "-" — and with them their SP text and an
        // IDEO_SPACE (out.anchors was length 5, and
        // out.gaps[3].latin held the orphaned "-314").
        // POST-FIX: the no-op is identity.
        expect(b.anchors).toHaveLength(7);
        expect(out).toEqual(b);
        const spText =
          "\u{F1941}\u{F1990}\u{F196C}\u{F1991}" +
          STACK +
          "axxq　\u{F1990}-\u{F1991}314　" +
          "\u{F1990}-\u{F196C}\u{F1991}";
        expect(renderSp(b).text).toBe(spText);
        expect(renderSp(out).text).toBe(spText);
        // and it is a true fixed point, not a one-step
        // coincidence
        expect(latinNoOp(out)).toEqual(out);
      }
    );
  }
);

// NOT a carve-out and NOT a defect — a normal-form
// CANONICALIZATION (see the NOT-CARVE-OUTS note in
// test/edit-corpus.ts). Found when the oracle-4a'
// fallthrough was removed, which is what had been
// swallowing it.
describe(
  "gap.latin interior to an ATOMIZING cartouche " +
    "re-homes outside the span, in one step",
  () => {
    it(
      "content is byte-preserved, anchors/spans/gap.sp " +
        "are untouched, and the second no-op is an " +
        "identity",
      () => {
        // The cartouche covers [verbatim, word]. Its
        // projected name is non-empty ("T"), so it
        // ATOMIZES — and renderLatin then emits that
        // name and nothing else for the whole span. The
        // "- " stored in gaps[2].latin, between the two
        // covered anchors, is therefore unreachable
        // through the Latin projection: no parse can
        // see it and no edit can address it.
        const b: Block = {
          anchors: [
            {
              kind: "verbatim",
              text: "-",
              marked: true,
            },
            { kind: "word", word: "toki" },
            {
              kind: "verbatim",
              text: "-",
              marked: true,
            },
            {
              kind: "verbatim",
              text: "-",
              marked: true,
            },
          ],
          gaps: [
            { sp: "  ", latin: "" },
            { sp: "", latin: "" },
            { sp: STACK, latin: "- " },
            { sp: "", latin: " " },
            { sp: "", latin: "" },
          ],
          spans: [
            cart(0, 0),
            cart(1, 2),
            cart(2, 2),
            cart(3, 3),
          ],
        };
        expect(checkBlock(b)).toEqual([]);
        // the interior "- " is invisible: the span
        // renders as its name alone
        expect(renderLatin(b).text).toBe("-T -");

        const once = latinNoOp(b);
        // ...and the normal form re-homes it OUTSIDE
        // the span, where it is visible again
        expect(once.gaps.map((g) => g.latin)).toEqual([
          "",
          "",
          "",
          " ",
          " -",
        ]);
        expect(renderLatin(once).text).toBe("-T - -");
        // BYTE-PRESERVED: the same latin characters, in
        // the same order, just outside the atom
        expect(
          b.gaps.map((g) => g.latin).join("")
        ).toBe("-  ");
        expect(
          once.gaps.map((g) => g.latin).join("")
        ).toBe("  -");
        // ...and NOTHING else moved: anchors, spans and
        // every gap.sp are byte-identical, so no span is
        // created or destroyed and the SP
        // pane does not change at all.
        expect(once.anchors).toEqual(b.anchors);
        expect(once.spans).toEqual(b.spans);
        expect(once.gaps.map((g) => g.sp)).toEqual(
          b.gaps.map((g) => g.sp)
        );
        expect(renderSp(once).text).toBe(
          renderSp(b).text
        );

        // ONE STEP: the second no-op is an identity, so
        // this is a canonicalization and not a ratchet.
        expect(latinNoOp(once)).toEqual(once);
      }
    );
  }
);
